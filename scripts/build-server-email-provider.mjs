// The server and desktop must use identical SMTP interpretation and partial-result handling.
// Commit the generated standalone module so the production server needs no compiler/install step.
import {build} from 'esbuild'
import {readFileSync,writeFileSync} from 'node:fs'
import {fileURLToPath} from 'node:url'
const outfile=new URL('../billing-server/leadsangel-provider.mjs',import.meta.url)
const result=await build({stdin:{contents:"export { verifyEmailAddressesWithLeadsAngel, parseLeadsAngelResult } from './electron/leadsangel.ts'",resolveDir:fileURLToPath(new URL('..',import.meta.url)),loader:'ts'},bundle:true,platform:'node',format:'esm',target:'node22',write:false,banner:{js:'// Generated by scripts/build-server-email-provider.mjs. Edit electron/leadsangel.ts, then regenerate.'}})
const source=result.outputFiles[0].text
if(process.argv.includes('--check')){
  // Git may check out the generated file with Windows line endings.
  if(readFileSync(outfile,'utf8').replace(/\r\n/g,'\n')!==source.replace(/\r\n/g,'\n'))throw new Error('Server SMTP provider is stale. Run node scripts/build-server-email-provider.mjs.')
}else writeFileSync(outfile,source)
